/**
 * Notifications API boundary: total parsers for prefs, events, history and
 * frames, plus thin `fetch` wrappers for the routes whose request/response
 * shapes the generated client cannot express (prefs and push subscriptions are
 * `unknown` in the contract).
 */
import { isRecord } from "./guards";
import type { paths } from "./schema";

type HistoryPayload = NonNullable<
  paths["/api/system/notifications/history"]["get"]["responses"][200]["content"]["application/json"]
>;
type DevicePayload = NonNullable<
  paths["/api/system/notifications/devices"]["get"]["responses"][200]["content"]["application/json"]
>;
type DevicesPutBody = NonNullable<
  paths["/api/system/notifications/devices"]["put"]["requestBody"]
>["content"]["application/json"];

export type NotificationHistoryEntry = HistoryPayload["entries"][number];
export type NotificationEvent = NotificationHistoryEntry["event"];
export type NotificationEventType = NotificationEvent["type"];
export type NotificationType = Exclude<NotificationEventType, "test">;
export type NotificationDeviceInfo = Pick<DevicePayload, "publicKey" | "subscribed">;
export type PresenceReport = NonNullable<
  paths["/api/system/notifications/presence"]["post"]["requestBody"]
>["content"]["application/json"];

export const NOTIFICATION_TYPES: readonly NotificationType[] = [
  "completed",
  "input",
  "error",
  "modelSwitch",
];

const EVENT_TYPES: readonly NotificationEventType[] = [...NOTIFICATION_TYPES, "test"];

/** Mirrors core's prefs, which the contract leaves `unknown` over the wire. */
export interface NotificationPrefs {
  enabled: boolean;
  types: Record<NotificationType, boolean>;
  whenActive: "toast" | "system";
  locale: string;
}

export const DEFAULT_NOTIFICATION_PREFS: NotificationPrefs = {
  enabled: false,
  types: { completed: true, input: true, error: true, modelSwitch: false },
  whenActive: "toast",
  locale: "en",
};

export interface NotificationMessage {
  kind: "toast" | "os";
  event: NotificationEvent;
}

export interface RenderedNotification {
  title: string;
  body: string;
  url: string;
  tag: string;
  sessionId: string;
}

/** Client and device ids generated by the browser and validated by the server. */
const NOTIFICATION_ID_PATTERN = /^[A-Za-z0-9_-]{8,64}$/;
const LOCALE_PATTERN = /^[A-Za-z-]{2,10}$/;

export function isValidNotificationId(value: unknown): value is string {
  return typeof value === "string" && NOTIFICATION_ID_PATTERN.test(value);
}

/** UUID when the browser exposes one (secure contexts), otherwise 16 random bytes. */
export function createNotificationId(): string {
  const cryptoApi = globalThis.crypto;
  if (typeof cryptoApi?.randomUUID === "function") {
    const uuid = cryptoApi.randomUUID();
    if (NOTIFICATION_ID_PATTERN.test(uuid)) return uuid;
  }
  const bytes = new Uint8Array(16);
  if (typeof cryptoApi?.getRandomValues === "function") cryptoApi.getRandomValues(bytes);
  else for (let index = 0; index < bytes.length; index += 1) bytes[index] = Math.floor(Math.random() * 256);
  let binary = "";
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}

export function parseNotificationPrefs(value: unknown): NotificationPrefs {
  const raw = isRecord(value) ? value : {};
  const rawTypes = isRecord(raw.types) ? raw.types : {};
  const types = { ...DEFAULT_NOTIFICATION_PREFS.types };
  for (const type of NOTIFICATION_TYPES) {
    const enabled = rawTypes[type];
    if (typeof enabled === "boolean") types[type] = enabled;
  }
  return {
    enabled: raw.enabled === true,
    types,
    whenActive: raw.whenActive === "system" ? "system" : "toast",
    locale: typeof raw.locale === "string" && LOCALE_PATTERN.test(raw.locale) ? raw.locale : "en",
  };
}

function isEventType(value: unknown): value is NotificationEventType {
  return typeof value === "string" && (EVENT_TYPES as readonly string[]).includes(value);
}

/** Parse one untrusted event; null when it cannot be rendered. */
export function parseNotificationEvent(value: unknown): NotificationEvent | null {
  if (!isRecord(value)) return null;
  const { type, sessionId } = value;
  if (!isEventType(type) || typeof sessionId !== "string") return null;
  const rawAliases = value.aliases;
  const aliases =
    Array.isArray(rawAliases) && rawAliases.every((alias) => typeof alias === "string")
      ? (rawAliases as string[])
      : null;
  return {
    type,
    sessionId,
    sessionName: typeof value.sessionName === "string" ? value.sessionName : null,
    ...(typeof value.detail === "string" ? { detail: value.detail } : {}),
    ...(typeof value.from === "string" ? { from: value.from } : {}),
    ...(typeof value.to === "string" ? { to: value.to } : {}),
    ...(aliases ? { aliases } : {}),
  };
}

/** Parse one persisted history row; null when the row is unusable. */
export function parseNotificationHistoryEntry(value: unknown): NotificationHistoryEntry | null {
  if (!isRecord(value) || typeof value.id !== "string") return null;
  const event = parseNotificationEvent(value.event);
  if (!event) return null;
  if (typeof value.at !== "number" || !Number.isFinite(value.at)) return null;
  if (typeof value.read !== "boolean") return null;
  return { id: value.id, event, at: value.at, read: value.read };
}

/** Parse a history payload, dropping malformed rows individually. */
export function parseNotificationHistory(value: unknown): NotificationHistoryEntry[] {
  if (!isRecord(value) || !Array.isArray(value.entries)) return [];
  return value.entries.flatMap((entry) => {
    const parsed = parseNotificationHistoryEntry(entry);
    return parsed ? [parsed] : [];
  });
}

/** Parse one SSE notification frame. */
export function parseNotificationFrame(value: unknown): NotificationMessage | null {
  if (!isRecord(value) || value.type !== "notification") return null;
  if (value.kind !== "toast" && value.kind !== "os") return null;
  const event = parseNotificationEvent(value.event);
  return event ? { kind: value.kind, event } : null;
}

export function countUnread(entries: readonly Pick<NotificationHistoryEntry, "read">[]): number {
  let unread = 0;
  for (const entry of entries) if (!entry.read) unread += 1;
  return unread;
}

