function translate(locale: string, key: keyof NotificationTexts, vars?: Record<string, string>): string {
  const dictionary = NOTIFICATION_TEXTS[locale] ?? ENGLISH_TEXTS;
  const template = dictionary[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? vars[name] ?? match : match));
}

const MAX_DETAIL = 180;
const MAX_TITLE = 100;

function clip(text: string, max = MAX_DETAIL): string {
  const flat = text.replace(/\s+/g, " ").trim();
  return flat.length > max ? `${flat.slice(0, max - 1)}…` : flat;
}

/** Title, body, click target and replace-tag for one event in the requested locale. */
export function renderNotification(event: NotificationEvent, locale: string): RenderedNotification {
  const detail = event.detail ? clip(event.detail) : "";
  let body: string;
  switch (event.type) {
    case "completed":
      body = translate(locale, "completedBody");
      break;
    case "input":
      body = detail
        ? translate(locale, "inputBody", { detail })
        : translate(locale, "inputBodyNoDetail");
      break;
    case "error":
      body = detail
        ? translate(locale, "errorBody", { detail })
        : translate(locale, "errorBodyNoDetail");
      break;
    case "modelSwitch":
      if (event.from && event.to) {
        body = detail
          ? translate(locale, "modelSwitchBody", { from: event.from, to: event.to, detail })
          : translate(locale, "modelSwitchBodyNoDetail", { from: event.from, to: event.to });
      } else {
        body = detail;
      }
      break;
    case "test":
      body = translate(locale, "testBody");
      break;
  }
  return {
    title: (event.sessionName && clip(event.sessionName, MAX_TITLE)) || translate(locale, "untitledSession"),
    body,
    url: event.sessionId ? `/?session=${encodeURIComponent(event.sessionId)}` : "/",
    tag: `${event.sessionId}:${event.type}`,
    sessionId: event.sessionId,
  };
}

/** Turn a VAPID public key (base64url) into the byte array `pushManager.subscribe` expects. */
export function urlBase64ToUint8Array(base64Url: string): Uint8Array<ArrayBuffer> {
  const padding = "=".repeat((4 - (base64Url.length % 4)) % 4);
  const base64 = (base64Url + padding).replace(/-/g, "+").replace(/_/g, "/");
  const binary = atob(base64);
  const bytes = new Uint8Array(new ArrayBuffer(binary.length));
  for (let index = 0; index < binary.length; index += 1) bytes[index] = binary.charCodeAt(index);
  return bytes;
}

const JSON_HEADERS = { "content-type": "application/json" };

async function request(path: string, init?: RequestInit): Promise<unknown> {
  const response = await fetch(path, init);
  if (!response.ok) {
    let message = `HTTP ${response.status}`;
    try {
      const body: unknown = await response.json();
      if (isRecord(body) && typeof body.error === "string") message = body.error;
    } catch {
      // Non-JSON error bodies keep the status text.
    }
    throw new Error(message);
  }
  if (response.status === 204) return undefined;
  const text = await response.text();
  if (!text) return undefined;
  try {
    return JSON.parse(text) as unknown;
  } catch {
    return undefined;
  }
}

function jsonBody(method: "POST" | "PUT" | "PATCH", value: unknown): RequestInit {
  return { method, headers: JSON_HEADERS, body: JSON.stringify(value) };
}

export async function fetchNotificationHistory(signal?: AbortSignal): Promise<NotificationHistoryEntry[]> {
  const data = await request("/api/system/notifications/history", signal ? { signal } : {});
  return parseNotificationHistory(data);
}

export async function markNotificationHistoryRead(ids: readonly string[]): Promise<void> {
  await request("/api/system/notifications/history", jsonBody("PATCH", { ids }));
}

export async function deleteNotificationHistoryEntry(id: string): Promise<void> {
  const query = new URLSearchParams({ id });
  await request(`/api/system/notifications/history?${query.toString()}`, { method: "DELETE" });
}

export async function clearNotificationHistory(): Promise<void> {
  await request("/api/system/notifications/history?all=1", { method: "DELETE" });
}

export async function fetchNotificationDevice(deviceId: string): Promise<NotificationDeviceInfo> {
  const query = new URLSearchParams({ deviceId });
  const data = await request(`/api/system/notifications/devices?${query.toString()}`);
  if (!isRecord(data) || typeof data.publicKey !== "string" || typeof data.subscribed !== "boolean") {
    throw new Error("Unexpected notification device response");
  }
  return { publicKey: data.publicKey, subscribed: data.subscribed };
}

export interface SaveNotificationDeviceInput {
  deviceId: string;
  prefs: NotificationPrefs;
  /** Omitted keeps the subscription the server already stored. */
  subscription?: PushSubscriptionJSON;
}

export async function saveNotificationDevice(
  input: SaveNotificationDeviceInput,
): Promise<{ subscribed: boolean }> {
  const body: DevicesPutBody = {
    deviceId: input.deviceId,
    prefs: input.prefs,
    ...(input.subscription ? { subscription: input.subscription } : {}),
  };
  const data = await request("/api/system/notifications/devices", jsonBody("PUT", body));
  if (!isRecord(data) || typeof data.subscribed !== "boolean") {
    throw new Error("Unexpected notification device response");
  }
  return { subscribed: data.subscribed };
}

export async function reportNotificationPresence(report: PresenceReport): Promise<void> {
  await request("/api/system/notifications/presence", jsonBody("POST", report));
}

/** 502 means the push service refused; the thrown error carries the server's message. */
export async function sendTestNotification(deviceId: string): Promise<void> {
  await request("/api/system/notifications/test", jsonBody("POST", { deviceId }));
}
